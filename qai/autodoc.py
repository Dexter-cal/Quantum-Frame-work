"""
qai.doc -- auto-generated markdown documentation for any qai model.

Generates a human-readable markdown description of the model:
  - What it is (technique, family, hyperparameters)
  - What its inputs look like (schema, shape, dtype)
  - What its outputs look like
  - Training history (epochs, time, samples)
  - How to use it (code snippet)
  - How to bundle/load it (code snippet)
  - Known limitations / warnings

Usage:
    import qai
    m = qai.build(technique="random_forest", n_estimators=100)
    m.train(X, y)
    print(qai.doc(m))              # markdown string
    qai.doc(m, save="model.md")    # write to file

Works for any qai.Model AND any qai.AgentBase subclass. For agents,
the doc includes episode count, hyperparameter scheduler state, and
the agent's own explain() narrative.
"""
from __future__ import annotations
from typing import Optional
import numpy as np
import qai


def doc(model, save: Optional[str] = None) -> str:
    """Generate a markdown documentation string for `model`.

    Args:
        model: any qai.Model (from qai.build(...)) or qai.AgentBase subclass.
        save: optional path to write the doc to (in addition to returning it).

    Returns:
        Markdown-formatted documentation string.
    """
    tech = getattr(model, "technique", None)
    technique_name = getattr(tech, "name", "unknown") if tech else type(model).__name__
    family = getattr(tech, "family", "unknown") if tech else "agent"
    trained = bool(getattr(model, "is_trained", lambda: False)()) if hasattr(model, "is_trained") else False
    is_agent = hasattr(model, "run_episode") and hasattr(model, "scheduler")

    lines = []
    lines.append(f"# `{technique_name}` -- auto-generated documentation\n")
    lines.append(f"> Generated by `qai.doc(model)` on a `{type(model).__name__}` instance.\n")

    # === Identity ===
    lines.append("## Identity\n")
    lines.append(f"- **Class:** `{type(model).__name__}`")
    lines.append(f"- **Technique:** `{technique_name}`")
    lines.append(f"- **Family:** `{family}`")
    lines.append(f"- **Trained:** {trained}")
    if is_agent:
        lines.append(f"- **Type:** Learning agent (subclass of `qai.AgentBase`)")
    lines.append("")

    # === Hyperparameters ===
    lines.append("## Hyperparameters\n")
    if tech is not None:
        hparams_found = False
        for attr in ("hidden_dim", "epochs", "lr", "n_estimators", "max_depth",
                     "n_clusters", "n_components", "k", "alpha", "kernel",
                     "learning_rate", "gamma", "epsilon", "batch_size",
                     "weight_decay", "dropout", "vocab_size", "d_model",
                     "n_heads", "n_layers", "max_seq_len"):
            if hasattr(tech, attr):
                v = getattr(tech, attr)
                if v is None or isinstance(v, (int, float, str, bool, list, tuple)):
                    lines.append(f"- `{attr}` = `{v!r}`")
                    hparams_found = True
        if not hparams_found:
            lines.append("_(no standard hyperparameters exposed)_")
    if is_agent:
        try:
            sched = model.scheduler
            lines.append(f"- agent `hparams` = `{sched.params}`")
            lines.append(f"- agent `bounds` = `{getattr(sched, 'bounds', {})}`")
        except Exception:
            pass
    lines.append("")

    # === Inputs / Outputs ===
    lines.append("## Inputs / Outputs\n")
    schema = getattr(model, "input_schema", None)
    if schema is not None:
        lines.append(f"- **Input schema:** `{schema}`")
    else:
        lines.append("- **Input schema:** _(none declared -- model accepts raw arrays)_")
    output_schema = getattr(model, "output_schema", None)
    if output_schema is not None:
        lines.append(f"- **Output schema:** `{output_schema}`")
    else:
        # Infer output shape from training
        if trained:
            try:
                last_X = getattr(tech, "_last_X", None)
                if last_X is not None:
                    sample_pred = model.predict(last_X[:1])
                    if hasattr(sample_pred, "shape"):
                        lines.append(f"- **Output shape:** `{sample_pred.shape}` (inferred from a sample prediction)")
                    else:
                        lines.append(f"- **Output type:** `{type(sample_pred).__name__}`")
            except Exception:
                pass
    lines.append("")

    # === Training history ===
    lines.append("## Training history\n")
    history = getattr(model, "_history", None)
    if history:
        lines.append(f"- **Events logged:** {len(history)}")
        # Show the most recent few
        lines.append("- **Recent events:**")
        for ev in history[-5:]:
            ev_clean = {k: v for k, v in ev.items() if k != "details"}
            lines.append(f"  - `{ev_clean}`")
    elif is_agent:
        try:
            s = model.status() if callable(getattr(model, "status", None)) else {}
            n_ep = s.get("n_episodes_completed", s.get("episodes_completed", 0))
            n_succ = s.get("n_successes", s.get("successes", 0))
            tot_r = s.get("total_reward", 0.0)
            lines.append(f"- **Episodes completed:** {n_ep}")
            lines.append(f"- **Successful episodes:** {n_succ}")
            lines.append(f"- **Total reward:** {tot_r:.2f}")
            try:
                slope = model.scheduler.slope
                lines.append(f"- **Performance slope:** {slope:+.4f}")
            except Exception:
                pass
        except Exception:
            pass
    else:
        lines.append("_(no training history available)_")
    lines.append("")

    # === How to use ===
    lines.append("## How to use\n")
    lines.append("```python")
    lines.append("import qai")
    lines.append("import numpy as np")
    lines.append("")
    if is_agent:
        lines.append(f"# Load the agent (from a saved bundle)")
        lines.append(f"bundle = qai.load_bundle('my_agent.qmodel')")
        lines.append(f"agent = bundle.model")
        lines.append("")
        lines.append(f"# Run an episode in any qai.Environment")
        lines.append(f"env = qai.make_environment('puzzle_world')")
        lines.append(f"summary = agent.run_episode(env, max_steps=30, learn=True)")
        lines.append(f"print(summary)")
        lines.append("")
        lines.append(f"# Ask the agent to explain itself")
        lines.append(f"print(agent.explain())")
    else:
        lines.append(f"# Load the model (from a saved bundle)")
        lines.append(f"bundle = qai.load_bundle('my_model.qmodel')")
        lines.append(f"model = bundle.model")
        lines.append("")
        lines.append(f"# Predict on new data")
        lines.append(f"X_new = np.array([[1.0, 2.0, 3.0]])  # shape: (n_samples, n_features)")
        lines.append(f"prediction = model.predict(X_new)")
        lines.append(f"print(prediction)")
        lines.append("")
        lines.append(f"# Get an explanation")
        lines.append(f"explanation = model.explain(X_new[0])")
        lines.append(f"print(explanation)")
    lines.append("```\n")

    # === Bundle / save ===
    lines.append("## Bundle / save\n")
    lines.append("```python")
    lines.append("# Save the model with logic functions + signing")
    lines.append("qai.save_bundle(model, 'my_model.qmodel',")
    lines.append("    logic_fns=[...],       # optional @qai.logic functions")
    lines.append("    sign_key='my-secret',   # optional HMAC signing")
    lines.append("    description='What this model does')")
    lines.append("")
    lines.append("# Inspect a bundle without loading")
    lines.append("info = qai.inspect_bundle('my_model.qmodel')")
    lines.append("")
    lines.append("# Verify a signed bundle")
    lines.append("valid = qai.verify_bundle('my_model.qmodel', sign_key='my-secret')")
    lines.append("```\n")

    # === Agent's own narrative (if available) ===
    if is_agent and hasattr(model, "explain"):
        try:
            narrative = model.explain()
            if isinstance(narrative, str) and narrative.strip():
                lines.append("## Agent's self-description\n")
                lines.append("```")
                lines.append(narrative)
                lines.append("```\n")
        except Exception:
            pass

    # === Limitations ===
    lines.append("## Known limitations\n")
    if family == "deep_learning":
        lines.append("- Deep-learning techniques require PyTorch installed (`pip install torch`).")
    if family == "reinforcement":
        lines.append("- RL agents need an environment with `reset()`, `step(action)`, `available_actions()`, `done()`.")
    if not trained:
        lines.append("- **This model is not yet trained.** Call `model.train(X, y)` first.")
    if not is_agent and not trained:
        lines.append("- Predictions will fail until trained.")
    if not any(line.startswith("- ") for line in lines[-5:]):
        lines.append("_(no specific limitations identified)_")
    lines.append("")

    # === Footer ===
    lines.append("---")
    lines.append(f"_Generated by `qai.doc()` -- edit the model and re-run to refresh._")

    out = "\n".join(lines)
    if save:
        with open(save, "w", encoding="utf-8") as f:
            f.write(out)
    return out


__all__ = ["doc"]
