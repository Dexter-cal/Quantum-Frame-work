"""
generate_dataset.py
===================
Synthetic dataset generator for the Pulse cognitive-state AI.

Each row represents a single "reading" from a hypothetical user's biometric
+ behavioral sensors at a given moment, plus the ground-truth cognitive
state they were in at that moment.

7 features (all lightweight — obtainable from a smartwatch + OS-level
screen-time API, no medical-grade hardware required):

    hrv_ms             heart-rate variability in milliseconds (10-150)
                       higher = more relaxed / parasympathetic-dominant
    sleep_last_night_h hours of sleep the previous night (0-12)
    screen_time_min    minutes of screen exposure in the last hour (0-60)
    deep_work_min      minutes of uninterrupted focused work in the last
                       30 min (0-30) -- proxy for current flow-state momentum
    time_of_day_h      decimal hours since midnight (0-24)
    last_break_min_ago minutes since the last break (0-240)
    caffeine_mg        mg of caffeine consumed in the last 4 hours (0-300)

5 cognitive states (the prediction target):

    0  focus       engaged, on-task, moderate energy
    1  flow        deeply absorbed, peak performance
    2  stress      high arousal, low control
    3  fatigued    low energy, slow responses
    4  scattered   attention fragmented, task-switching

The label is generated by a hand-designed non-linear function that
captures realistic interactions:

  * High HRV + recent deep-work + daytime -> FLOW
  * Low HRV + high screen-time + caffeine -> STRESS
  * Low sleep + high last_break -> FATIGUED
  * High screen-time + low deep-work + afternoon -> SCATTERED
  * Default -> FOCUS

We then add 8% label noise to make the dataset realistic -- real
cognitive state is not perfectly predictable from sensors.
"""
from __future__ import annotations
import numpy as np
import json
import os

RNG_SEED = 42
N_TRAIN = 1500
N_VAL = 400
N_TEST = 400

FEATURE_NAMES = [
    "hrv_ms",
    "sleep_last_night_h",
    "screen_time_min",
    "deep_work_min",
    "time_of_day_h",
    "last_break_min_ago",
    "caffeine_mg",
]
STATE_NAMES = ["focus", "flow", "stress", "fatigued", "scattered"]
STATE_TO_IDX = {n: i for i, n in enumerate(STATE_NAMES)}


def sample_reading(rng: np.random.Generator) -> np.ndarray:
    """Sample a single reading's features from realistic marginal distributions."""
    hrv = rng.uniform(10, 150)
    sleep = rng.normal(7, 1.5)  # most people get ~7h
    sleep = float(np.clip(sleep, 0, 12))
    screen = rng.uniform(0, 60)
    deep_work = rng.uniform(0, 30)
    # time of day biased toward working hours (8am-10pm)
    if rng.random() < 0.75:
        tod = rng.uniform(8, 22)
    else:
        tod = rng.uniform(0, 24)
    last_break = rng.uniform(0, 240)
    caffeine = rng.choice([0, 0, 0, 50, 80, 100, 150, 200, 250, 300])
    return np.array([hrv, sleep, screen, deep_work, tod, last_break, caffeine],
                    dtype=np.float32)


def label_for(reading: np.ndarray, rng: np.random.Generator) -> int:
    """Hand-designed non-linear labeling function with realistic interactions."""
    hrv, sleep, screen, deep_work, tod, last_break, caffeine = reading

    # FLOW: high HRV (>70) + recent deep work (>15) + daytime (9-21) + decent sleep
    if hrv > 70 and deep_work > 15 and 9 <= tod <= 21 and sleep > 6:
        # If caffeine is moderate and last break is recent, definitely flow
        if 50 <= caffeine <= 200 and last_break < 90:
            return STATE_TO_IDX["flow"]
        # Otherwise flow is still likely
        if rng.random() < 0.7:
            return STATE_TO_IDX["flow"]

    # STRESS: low HRV (<35) + high screen time (>40) + high caffeine (>150)
    if hrv < 35 and screen > 40 and caffeine > 150:
        return STATE_TO_IDX["stress"]
    # Also stressed if very low HRV + late at night + caffeine
    if hrv < 30 and tod >= 22 and caffeine > 100:
        return STATE_TO_IDX["stress"]

    # FATIGUED: poor sleep (<5.5) + last break > 120 min ago + low caffeine
    if sleep < 5.5 and last_break > 120 and caffeine < 50:
        return STATE_TO_IDX["fatigued"]
    # Also fatigued if very poor sleep regardless
    if sleep < 4.5 and rng.random() < 0.6:
        return STATE_TO_IDX["fatigued"]

    # SCATTERED: high screen time (>45) + low deep work (<5) + afternoon (13-18)
    if screen > 45 and deep_work < 5 and 13 <= tod <= 18:
        return STATE_TO_IDX["scattered"]
    # Also scattered if last break was very long ago + high screen
    if last_break > 180 and screen > 35:
        return STATE_TO_IDX["scattered"]

    # Default: FOCUS
    return STATE_TO_IDX["focus"]


def generate(n: int, rng: np.random.Generator, noise_rate: float = 0.08):
    """Generate n readings with labels (with `noise_rate` label noise)."""
    X = np.stack([sample_reading(rng) for _ in range(n)])
    y = np.array([label_for(X[i], rng) for i in range(n)])
    # Add label noise
    n_noisy = int(n * noise_rate)
    if n_noisy > 0:
        noisy_idx = rng.choice(n, n_noisy, replace=False)
        y[noisy_idx] = rng.integers(0, len(STATE_NAMES), size=n_noisy)
    return X, y


def main():
    rng = np.random.default_rng(RNG_SEED)
    out_dir = os.path.join(os.path.dirname(__file__), "..", "data")
    os.makedirs(out_dir, exist_ok=True)

    splits = {"train": (N_TRAIN, 0.10), "val": (N_VAL, 0.10), "test": (N_TEST, 0.10)}
    summary = {}
    for split_name, (n, noise) in splits.items():
        X, y = generate(n, rng, noise_rate=noise)
        out_path = os.path.join(out_dir, f"pulse_{split_name}.npz")
        np.savez(out_path, X=X, y=y, feature_names=np.array(FEATURE_NAMES),
                 state_names=np.array(STATE_NAMES))
        # Class distribution
        counts = np.bincount(y, minlength=len(STATE_NAMES))
        summary[split_name] = {
            "n": n,
            "path": out_path,
            "class_distribution": {STATE_NAMES[i]: int(counts[i]) for i in range(len(STATE_NAMES))},
        }
        print(f"[{split_name}] {n} samples -> {out_path}")
        print(f"  class dist: {dict(zip(STATE_NAMES, counts.tolist()))}")

    meta_path = os.path.join(out_dir, "metadata.json")
    with open(meta_path, "w") as f:
        json.dump({
            "feature_names": FEATURE_NAMES,
            "state_names": STATE_NAMES,
            "state_to_idx": STATE_TO_IDX,
            "splits": summary,
            "rng_seed": RNG_SEED,
            "description": __doc__.split("\n\n")[0].strip(),
        }, f, indent=2)
    print(f"\nMetadata -> {meta_path}")


if __name__ == "__main__":
    main()
